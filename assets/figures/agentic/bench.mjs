import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as k from "../cellular/iso-kit.mjs";

export { k };
const HERE = dirname(fileURLToPath(import.meta.url));
export const DEG = Math.PI / 180;
export const unit = (deg) => [Math.cos(deg * DEG), Math.sin(deg * DEG)];

export function kitFor(P) {
  const VIEW = k.towardViewer(P);
  const at = (p) => k.iso(p, P);
  const S = (paths, style) => k.solidSvg(paths, style);
  const L = (d, style) => k.lineSvg(d, style);
  const D = (pts, style) => k.dotsSvg(pts, style);
  const poly = (pts, closed = false) => k.pathOf(pts.map(at), closed);
  const depth = ([x, y, z = 0]) => k.depthOf([x, y, z], P);
  const byDepth = (pts) => [...pts].sort((a, b) => depth(a) - depth(b));
  const slab = (plan, z, h, steps = 4, bevel = 0.4) => k.slabOf(plan, z, h, P, steps, bevel);
  const cyl = (x, y, r, z, h, steps = 28, bevel = 0) => k.cylinder(x, y, r, z, h, P, steps, bevel);
  const plan = (cx, cy, w, d, r = 1) => ({ x: cx - w / 2, y: cy - d / 2, w, d, r });
  // a vertical face at y = yF (facing +y), local coordinates (x, -z) for flat drawings on it
  const faceY = (x0, yF, z0) => k.sideMatrix([x0, yF], z0, P, "left");
  const faceX = (xF, y0, z0) => k.sideMatrix([xF, y0], z0, P, "right");
  const top = (x0, y0, z) => k.topMatrix([x0, y0], z, P, "x");
  const vec = (v) => k.axisVector(P, v);
  return { P, VIEW, at, S, L, D, poly, depth, byDepth, slab, cyl, plan, faceY, faceX, top, vec };
}

// The bench every scene stands on: plate on four feet, groove, corner screws, optional ruler strip and label plate.
export function plinth(K, PLATE, { foot = 14, strip = null, label = null } = {}) {
  const { P, S, L, D, at, byDepth } = K;
  const out = [`<path class="iso-halo" d="${k.haloOf(PLATE, -foot, foot, P)}"/>`];
  for (const [x, y] of byDepth(k.corners(PLATE, 20))) {
    out.push(S(k.cylinder(x, y, 6.4, -foot, 1.6, P, 28), { tone: "lo" }));
    out.push(S(k.cylinder(x, y, 5, -foot + 1.6, foot - 11.6, P, 28), { tone: "mid" }));
  }
  out.push(S(k.slabOf(PLATE, -10, 10, P, 8, 1.6), { tone: "mid" }));
  out.push(L(k.planOutline(k.insetPlan(PLATE, 5), 0, P), { tone: "lo" }));
  const screws = k.corners(PLATE, 10);
  out.push(L(screws.map(([x, y]) => k.ring(x, y, 2.2, 0, P, 16)).join(""), { tone: "lo" }));
  out.push(D(screws.map(([x, y]) => at([x, y, 0])), { size: 0.5 }));
  if (strip) {
    out.push(S(k.slabOf(strip, 0, 0.6, P, 3), { tone: "lo", crease: "none" }));
    const t = strip.axis === "y"
      ? k.topTicks(strip.y + 4, strip.y + strip.d - 4, 4, 5, strip.x + 0.8, 0.6, [2, 3.6], P, "y")
      : k.topTicks(strip.x + 4, strip.x + strip.w - 4, 4, 5, strip.y + 0.8, 0.6, [2, 3.6], P);
    out.push(L(t.minor, { tone: "lo" }), L(t.major, { tone: "mid" }));
  }
  if (label) {
    const lp = label;
    out.push(S(k.slabOf(lp, 0, 0.8, P, 4, 0.3), { tone: "mid" }));
    out.push(L(k.planOutline(k.insetPlan(lp, 1.6), 0.8, P), { tone: "faint" }));
    out.push(L([0, 1, 2].map((i) => k.lineOnTop([lp.x + 4, lp.y + 4 + i * 3], [lp.x + lp.w - 6 - i * 3, lp.y + 4 + i * 3], 0.8, P)).join(""), { tone: "lo", free: true }));
    out.push(D([at([lp.x + lp.w - 2.6, lp.y + 2.6, 0.8]), at([lp.x + lp.w - 2.6, lp.y + lp.d - 2.6, 0.8])], { size: 0.45 }));
  }
  return out.join("");
}

// Strip the dark @media block (balanced braces) and turn the explicit dark rule into a #dark:target rule.
function posterCss(text) {
  let s = text;
  for (;;) {
    const i = s.indexOf("@media (prefers-color-scheme:dark)");
    if (i < 0) break;
    let depthB = 0, j = s.indexOf("{", i);
    for (; j < s.length; j++) { if (s[j] === "{") depthB++; else if (s[j] === "}") { depthB--; if (!depthB) break; } }
    s = s.slice(0, i) + s.slice(j + 1);
  }
  return s.replace(/:root\[data-theme="dark"\] \.iso\b/g, ".iso:has(#dark:target)").replace(/@media \(prefers-reduced-motion:reduce\)\{[^}]*\}\}/g, "");
}
export function writeScene(dir, { P, svg, data = {}, sceneCss, poster }) {
  writeFileSync(join(dir, "art.js"), `// Generated by build.mjs. Do not edit by hand.\nexport const P = ${JSON.stringify(P)};\nexport const DATA = ${JSON.stringify(data)};\nexport const SVG = ${JSON.stringify(svg)};\n`);
  const kitCss = readFileSync(join(HERE, "../cellular/mast.css"), "utf8");
  const css = posterCss(kitCss + "\n" + sceneCss).replace(/\n/g, "") + ".iso{background:var(--anatomy-card)}";
  let s = poster(svg);
  s = s.replace('class="iso-svg"', 'class="iso-svg iso"').replace(/^<svg([^>]*)>/, `<svg$1><style>${css}</style><g id="dark"/><rect width="100%" height="100%" fill="var(--anatomy-card)"/>`);
  writeFileSync(join(dir, "poster.svg"), s);
}
